import os
import smtplib
import html
from datetime import datetime
from email.message import EmailMessage

import pandas as pd
from dotenv import load_dotenv

# 1. Load environment variables
load_dotenv()

GMAIL_ADDRESS = os.getenv("GMAIL_ADDRESS")
GMAIL_APP_PASSWORD = os.getenv("GMAIL_APP_PASSWORD")
RECIPIENT_EMAIL = os.getenv("RECIPIENT_EMAIL")

if not all([GMAIL_ADDRESS, GMAIL_APP_PASSWORD, RECIPIENT_EMAIL]):
    raise ValueError("Missing Gmail credentials in .env file")

# 2. Read sales data
df = pd.read_csv("sales.csv")

# 3. Calculate metrics
df["revenue"] = df["quantity_sold"] * df["price"]

total_revenue = df["revenue"].sum()
total_transactions = df["transaction_id"].nunique()

item_sales = df.groupby("item_name")["quantity_sold"].sum()

top_selling_item = item_sales.idxmax()
top_selling_quantity = item_sales.max()

# 4. Check inventory
inventory = df.groupby("item_name").agg(
    stock_on_hand=("stock_on_hand", "last"),
    restock_level=("restock_level", "last")
)

low_stock = inventory[
    inventory["stock_on_hand"] <= inventory["restock_level"]
]

# 5. Prepare low-stock HTML
if low_stock.empty:
    stock_html = """
    <p style="color:green;">
        All items have sufficient stock.
    </p>
    """
else:
    stock_rows = ""

    for item, row in low_stock.iterrows():
        stock_rows += f"""
        <tr>
            <td>{html.escape(str(item))}</td>
            <td>{row['stock_on_hand']}</td>
            <td>{row['restock_level']}</td>
            <td style="color:red;">RESTOCK</td>
        </tr>
        """

    stock_html = f"""
    <table width="100%" cellpadding="10"
           cellspacing="0" style="border-collapse:collapse;">
        <tr style="background:#eeeeee;">
            <th align="left">Item</th>
            <th>Current Stock</th>
            <th>Restock Level</th>
            <th>Status</th>
        </tr>
        {stock_rows}
    </table>
    """

# 6. Create HTML email
report_date = datetime.now().strftime("%d %B %Y")

html_content = f"""
<html>
<body style="font-family:Arial,sans-serif;
             color:#333;background:#f5f5f5;padding:20px;">

<div style="max-width:650px;margin:auto;background:white;
            padding:25px;border-radius:10px;">

    <h2 style="color:#176B45;">
        Daily Sales Report
    </h2>

    <p>{report_date}</p>

    <hr>

    <h3>Sales Performance</h3>

    <table width="100%" cellpadding="12">
        <tr>
            <td>
                <b>Total Revenue</b><br>
                <span style="font-size:24px;color:#176B45;">
                    KES {total_revenue:,.2f}
                </span>
            </td>
            <td>
                <b>Transactions</b><br>
                <span style="font-size:24px;">
                    {total_transactions}
                </span>
            </td>
        </tr>
    </table>

    <hr>

    <h3>Top-Selling Item</h3>

    <p style="font-size:18px;">
        <b>{html.escape(str(top_selling_item))}</b>
        - {top_selling_quantity} units sold
    </p>

    <hr>

    <h3>Inventory Alerts</h3>

    {stock_html}

    <br>

    <p style="font-size:12px;color:#888;">
        Automatically generated by Daily Sales Reporter.
    </p>

</div>
</body>
</html>
"""

# 7. Create email message
message = EmailMessage()

message["Subject"] = f"Daily Sales Report - {report_date}"
message["From"] = GMAIL_ADDRESS
message["To"] = RECIPIENT_EMAIL

message.set_content(
    f"""Daily Sales Report - {report_date}

Total Revenue: KES {total_revenue:,.2f}
Transactions: {total_transactions}
Top Selling Item: {top_selling_item}
Quantity Sold: {top_selling_quantity}

Low Stock Items:
{low_stock.to_string() if not low_stock.empty else 'None'}
"""
)

message.add_alternative(html_content, subtype="html")

# 8. Send email through Gmail SMTP
with smtplib.SMTP("smtp.gmail.com", 587) as server:
    server.starttls()
    server.login(GMAIL_ADDRESS, GMAIL_APP_PASSWORD)
    server.send_message(message)

print("\nSales report successfully emailed!")
print(f"Recipient: {RECIPIENT_EMAIL}")